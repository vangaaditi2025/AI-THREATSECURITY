import json
import os
from datetime import datetime, timezone
from pathlib import Path
import streamlit as st
from sqlalchemy import create_engine, text

DB_PATH = Path("data/threatguard.db")

def _db_url():
    url = os.getenv("DATABASE_URL", "")
    if not url:
        try:
            url = st.secrets.get("DATABASE_URL", "")
        except Exception:
            pass
    if url:
        if url.startswith("postgresql://"):
            url = url.replace("postgresql://", "postgresql+psycopg://", 1)
        elif url.startswith("postgres://"):
            url = url.replace("postgres://", "postgresql+psycopg://", 1)
        return url
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    return f"sqlite:///{DB_PATH}"

engine = create_engine(
    _db_url(),
    pool_pre_ping=True,
    connect_args={"check_same_thread": False} if _db_url().startswith("sqlite") else {},
)

def init_db():
    with engine.begin() as c:
        if engine.dialect.name == "sqlite":
            c.execute(text("""CREATE TABLE IF NOT EXISTS users(
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                name TEXT NOT NULL,
                email TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL,
                is_admin INTEGER NOT NULL DEFAULT 0,
                created_at TEXT NOT NULL
            )"""))
            c.execute(text("""CREATE TABLE IF NOT EXISTS scans(
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                user_id INTEGER,
                scan_type TEXT NOT NULL,
                target TEXT,
                risk TEXT NOT NULL,
                score INTEGER NOT NULL,
                result_json TEXT,
                created_at TEXT NOT NULL
            )"""))
        else:
            c.execute(text("""CREATE TABLE IF NOT EXISTS users(
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                email TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL,
                is_admin INTEGER NOT NULL DEFAULT 0,
                created_at TEXT NOT NULL
            )"""))
            c.execute(text("""CREATE TABLE IF NOT EXISTS scans(
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER,
                scan_type TEXT NOT NULL,
                target TEXT,
                risk TEXT NOT NULL,
                score INTEGER NOT NULL,
                result_json TEXT,
                created_at TEXT NOT NULL
            )"""))

def create_user(name, email, password):
    from utils.auth import hash_password
    email = email.strip().lower()
    with engine.begin() as c:
        exists = c.execute(text("SELECT COUNT(*) FROM users WHERE email=:email"), {"email": email}).scalar()
        if exists:
            return False
        total = c.execute(text("SELECT COUNT(*) FROM users")).scalar()
        c.execute(text("""INSERT INTO users(name,email,password_hash,is_admin,created_at)
                          VALUES(:name,:email,:password_hash,:is_admin,:created_at)"""), {
            "name": name.strip(), "email": email, "password_hash": hash_password(password),
            "is_admin": 1 if total == 0 else 0,
            "created_at": datetime.now(timezone.utc).isoformat()
        })
    return True

def authenticate_user(email, password):
    from utils.auth import verify_password
    with engine.connect() as c:
        row = c.execute(text("SELECT * FROM users WHERE email=:email"), {"email": email.strip().lower()}).mappings().first()
    if row and verify_password(password, row["password_hash"]):
        return dict(row)
    return None

def is_admin(user_id):
    with engine.connect() as c:
        row = c.execute(text("SELECT is_admin FROM users WHERE id=:id"), {"id": user_id}).first()
    return bool(row and row[0])

def save_scan(user_id, scan_type, target, risk, score, result):
    with engine.begin() as c:
        c.execute(text("""INSERT INTO scans(user_id,scan_type,target,risk,score,result_json,created_at)
                          VALUES(:user_id,:scan_type,:target,:risk,:score,:result_json,:created_at)"""), {
            "user_id": user_id, "scan_type": scan_type, "target": target,
            "risk": risk, "score": score, "result_json": json.dumps(result),
            "created_at": datetime.now(timezone.utc).isoformat()
        })

def get_scans(user_id=None, limit=50):
    with engine.connect() as c:
        if user_id is None:
            rows = c.execute(text("SELECT * FROM scans ORDER BY id DESC LIMIT :limit"), {"limit": limit}).mappings().all()
        else:
            rows = c.execute(text("SELECT * FROM scans WHERE user_id=:user_id ORDER BY id DESC LIMIT :limit"),
                             {"user_id": user_id, "limit": limit}).mappings().all()
    return [dict(x) for x in rows]

def get_stats(user_id=None):
    with engine.connect() as c:
        if user_id is None:
            total = c.execute(text("SELECT COUNT(*) FROM scans")).scalar()
            threats = c.execute(text("SELECT COUNT(*) FROM scans WHERE risk IN ('High','Critical')")).scalar()
            safe = c.execute(text("SELECT COUNT(*) FROM scans WHERE risk='Low'")).scalar()
        else:
            params = {"user_id": user_id}
            total = c.execute(text("SELECT COUNT(*) FROM scans WHERE user_id=:user_id"), params).scalar()
            threats = c.execute(text("SELECT COUNT(*) FROM scans WHERE user_id=:user_id AND risk IN ('High','Critical')"), params).scalar()
            safe = c.execute(text("SELECT COUNT(*) FROM scans WHERE user_id=:user_id AND risk='Low'"), params).scalar()
    return {"total": total, "threats": threats, "safe": safe, "high": threats}
